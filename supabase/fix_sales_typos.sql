-- ------------------------------------------------------------
-- [1] ดูก่อนว่าจะแก้อะไร (รันเฉพาะบล็อกนี้ก่อนก็ได้)
-- ------------------------------------------------------------
select id, branch_id, sale_date, shift,
       target_total  as "เป้าที่คีย์ไว้",
       sales_total   as "ยอดจริง",
       delivery_bills as "บิลเดลิเวอรี",
       edited_at     as "เคยแก้เมื่อ"
  from public.sales_daily
 where id in (9010, 8977, 9016, 11032)
 order by sale_date, shift;

-- ------------------------------------------------------------
-- [2] เป้าที่จุดทศนิยมหาย 1 รายการ
--     สาขา หน้า รพ.หล่มสัก · 23/10/69 ผลัดดึก
--     คีย์ไว้ 982,759 บาท — ค่ากลางของผลัดดึกสาขานี้ราว 8,163 และยอดจริงวันนั้น 8,527.71
--     อ่านว่าจุดทศนิยมหายสองตำแหน่ง → 9,827.59  (แบบเดียวกับ 2285876 → 22,858.76 ที่แก้ไปแล้ว)
--
--     ★ ถ้าดูบิล/ใบเป้าจริงแล้วเป็นเลขอื่น ให้แก้ 9827.59 ในบรรทัดล่างก่อนรัน
-- ------------------------------------------------------------
update public.sales_daily
   set orig = coalesce(orig, '{}'::jsonb) || jsonb_build_object(
                'target_total', target_total,
                'sales_total',  sales_total,
                'customers',    customers,
                'per_head',     per_head),
       target_total = 9827.59,
       edited_at = now(),
       edited_by = 'สำนักงานใหญ่ (SQL)',
       edit_note = 'เป้าคีย์ผิด จุดทศนิยมหาย 982759 → 9827.59'
 where id = 9010
   and target_total = 982759;        -- กันรันซ้ำ/กันทับค่าที่แก้มือไปแล้ว

-- ------------------------------------------------------------
-- [3] ช่อง "จำนวนบิลเดลิเวอรี" ที่กรอกยอดเงินลงไป 3 แถว
--     สาขา ถนนสามัคคีชัยหล่มสัก ผลัดเช้า — ปกติกะละราว 12 บิล
--       22/10/69  คีย์ไว้ 1,946
--       23/10/69  คีย์ไว้ 1,946
--        4/11/69  คีย์ไว้ 5,026
--     จำนวนบิลจริงไม่มีทางเดาได้จากยอดเงิน → ตั้งเป็น "ไม่มีข้อมูล" (null)
--     ไม่ตั้งเป็น 0 เพราะ 0 จะถูกนับเป็น "ขายไม่ได้เลย" แล้วกดค่าเฉลี่ยของคนในกะนั้นลง
--
--     ★ ถ้าหาจำนวนบิลจริงจากระบบเดลิเวอรีได้ ใส่แทน null ได้เลย
-- ------------------------------------------------------------
update public.sales_daily
   set orig = coalesce(orig, '{}'::jsonb) || jsonb_build_object('delivery_bills', delivery_bills),
       delivery_bills = null,
       edited_at = now(),
       edited_by = 'สำนักงานใหญ่ (SQL)',
       edit_note = 'ช่องจำนวนบิลเดลิเวอรีถูกกรอกเป็นยอดเงิน — ล้างเป็นไม่มีข้อมูล'
 where id in (8977, 9016, 11032)
   and delivery_bills > 1000;        -- กันรันซ้ำ

-- ------------------------------------------------------------
-- [4] ตรวจผลหลังแก้
-- ------------------------------------------------------------
select id, branch_id, sale_date, shift, target_total, sales_total, delivery_bills,
       edited_by, edit_note, orig
  from public.sales_daily
 where id in (9010, 8977, 9016, 11032)
 order by sale_date, shift;

select 'fix_sales_typos.sql done' as result;

