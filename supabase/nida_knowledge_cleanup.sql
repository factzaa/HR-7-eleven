-- ⚠ ก่อนอื่น — ผมเตือนตัวเลขผิดไว้รอบก่อน ขอแก้ให้ตรง
--   ผมบอกว่าคลัง "ชนเพดาน 22,000 ตัวอักษรแล้ว" โดยเดาจากคอมเมนต์ในโค้ดที่เขียนไว้ตั้งแต่ ก.ย.
--   พอวัดของจริงพบว่า หมวดที่เป็นกฎการทำงาน (policy 4 + standard 14) รวมกันแค่ 12,636 ตัวอักษร
--   ยังเหลือที่ว่างอีกเกือบหมื่น ชุดความรู้ใหม่ 12 รายการ (3,744) จึงเข้าได้สบาย ไม่ดันของเก่าตก
--
--   แต่พอไล่ดูจริงกลับเจอปัญหาคนละเรื่อง ซึ่งใหญ่กว่า — อยู่ข้างล่าง
--
-- ต้องรันไฟล์นี้ไหม: รันก็ดี ไม่รันก็ไม่พัง (เป็นการจัดบ้าน ไม่ใช่แก้บั๊ก)
-- รันซ้ำได้ · ไม่ลบข้อมูลสักแถว
