-- ============================================================
-- ส่วนที่ 1 — ดูก่อนว่าจะแก้อะไร (ไม่เปลี่ยนอะไรทั้งสิ้น)
--   รันส่วนนี้ก่อน ดูชื่อใหม่ที่ระบบจะตั้งให้ ถ้าโอเคค่อยรันส่วนที่ 2
-- ============================================================

with n as (
  select id, category, title,
         regexp_replace(
           regexp_replace(content,
             '^[[:space:]*]*(\[?สรุป\]?)[::][[:space:]*]*|^[[:space:]*]*\[สรุป\][[:space:]*]*', '', 'i'),
           '[[:space:]]+', ' ', 'g') c
    from public.nida_knowledge
   where active and (title like '**%' or length(trim(title)) < 12)
), d as (
  select id, category, title,
         trim(both ' "“”*' from
           coalesce(
             substring(c from 'เอกสารนี้คือ[[:space:]]*["“]([^"”]{4,80})["”]'),   -- ชื่อในเครื่องหมายคำพูด = สะอาดที่สุด
             substring(c from 'เอกสารนี้คือ[[:space:]]*(.{6,80})'),
             left(c, 80))) raw
    from n
)
select id,
       category                                        as หมวด,
       title                                           as ชื่อเดิม,
       nullif(trim(both ' "“”*,.' from
         trim(regexp_replace(left(raw, 72), '[[:space:]][^[:space:]]*$', ''))), '') as ชื่อใหม่
  from d
 order by category, id;


-- ============================================================
-- ส่วนที่ 2 — ตั้งชื่อใหม่ให้รายการที่ชื่อใช้ไม่ได้
--
-- ปัญหา: ตอนนำเข้าเอกสาร PDF ชุด istore_document เมื่อ 22 ส.ค.
--   ตัวนำเข้าหยิบหัวข้อมาร์คดาวน์บรรทัดแรกมาเป็นชื่อ ซึ่งบังเอิญเป็น "**[สรุป]**" เหมือนกันหมด
--   ทำให้มีหลายรายการชื่อซ้ำกันเป๊ะและไม่บอกอะไรเลย
--
-- ทำไมถึงสำคัญทั้งที่หมวด training ไม่ได้ถูกฉีดเข้าพรอมต์
--   เวลา knowledge_search ค้นไม่เจอ โค้ดจะคืน "รายชื่อคู่มือที่นำเข้าไว้" ให้นิดาเลือกค้นต่อ
--   ถ้าในรายชื่อนั้นมี "**[สรุป]**" เรียงกันสิบกว่าอัน นิดาเลือกไม่ถูก และตอบผู้ใช้ไม่ได้ว่ามีอะไรบ้าง
--   ชื่อใหม่ดึงจากต้นเนื้อหา ซึ่งขึ้นต้นว่า "เอกสารนี้คือ ..." อยู่แล้วทุกรายการ
--
-- ไม่แตะ updated_at โดยตั้งใจ — ประวัติว่าบันทึกไว้เมื่อไหร่ต้องคงเดิม
-- ไม่แตะ content — แก้แค่ชื่อ
-- ============================================================

begin;

with n as (
  select id,
         regexp_replace(
           regexp_replace(content,
             '^[[:space:]*]*(\[?สรุป\]?)[::][[:space:]*]*|^[[:space:]*]*\[สรุป\][[:space:]*]*', '', 'i'),
           '[[:space:]]+', ' ', 'g') c
    from public.nida_knowledge
   where active and (title like '**%' or length(trim(title)) < 12)
), d as (
  select id,
         nullif(trim(both ' "“”*,.' from
           trim(regexp_replace(
             left(trim(both ' "“”*' from
               coalesce(
             substring(c from 'เอกสารนี้คือ[[:space:]]*["“]([^"”]{4,80})["”]'),   -- ชื่อในเครื่องหมายคำพูด = สะอาดที่สุด
             substring(c from 'เอกสารนี้คือ[[:space:]]*(.{6,80})'),
             left(c, 80))), 72),
             '[[:space:]][^[:space:]]*$', ''))), '') as newtitle
    from n
)
update public.nida_knowledge k
   set title = d.newtitle
  from d
 where k.id = d.id
   and d.newtitle is not null
   and length(d.newtitle) >= 12;      -- กันตั้งชื่อใหม่ที่สั้นจนไม่ต่างจากเดิม

commit;


