-- ============================================================
-- กองทุนสงเคราะห์ลูกจ้าง — เพิ่มคอลัมน์ที่ระบบเงินเดือนต้องใช้  (17 ก.ย. 69)
--
-- หักฝั่งลูกจ้าง (ค่าตั้งต้น 0.25%) คิดแบบเดียวกับประกันสังคม
-- ค่าตั้งค่ากลางเก็บใน payroll_config คีย์ 'welfare' (ระบบสร้างให้เองตอนกดบันทึกค่าตั้งค่า)
-- ดีฟอลต์คือ "ปิดใช้งาน" — ยังไม่หักจนกว่าจะไปเปิดที่หน้าตั้งค่าเงินเดือน
--
-- รัน SQL นี้ก่อนใช้งาน ไม่งั้นการบันทึกรอบเงินเดือนจะ error เพราะไม่มีคอลัมน์
-- ปลอดภัย: เป็นการ "เพิ่มคอลัมน์" เท่านั้น ไม่ลบ ไม่แก้ข้อมูลเดิม · รันซ้ำได้
-- ============================================================

-- 1) ยอดหักกองทุนสงเคราะห์ของแต่ละคนในแต่ละรอบ
alter table payroll_items
  add column if not exists welfare numeric not null default 0;

-- 2) เปิด/ปิดการหักรายคน (เหมือน sso_enabled)
alter table payroll_profiles
  add column if not exists welfare_enabled boolean not null default true;

-- 3) ตรวจผล — ควรเห็นทั้ง 2 คอลัมน์
select table_name, column_name, data_type, column_default
  from information_schema.columns
 where (table_name = 'payroll_items'    and column_name = 'welfare')
    or (table_name = 'payroll_profiles' and column_name = 'welfare_enabled')
 order by table_name;

-- ============================================================
-- หมายเหตุ
--   • รอบเงินเดือนที่ปิดไปแล้วจะมี welfare = 0 ทั้งหมด (ยังไม่เคยหัก) — ถูกต้องแล้ว
--   • เปิดใช้งานเมื่อไร: หน้าเงินเดือน → ตั้งค่า → การ์ด "กองทุนสงเคราะห์ลูกจ้าง" → ติ๊กเปิดใช้งาน
--     แล้วรันรอบเงินเดือนใหม่ · รอบที่รันไปแล้วต้องรันใหม่ถึงจะมีรายการหักนี้
--   • ส่วนนี้คือเงินหักฝั่งลูกจ้างเท่านั้น เงินสมทบฝั่งนายจ้างไม่ได้อยู่ในสลิปพนักงาน
--     ถ้าต้องการรายงานยอดนำส่งรวม (ลูกจ้าง + นายจ้าง) ต้องทำเพิ่มอีกส่วนหนึ่ง
-- ============================================================
