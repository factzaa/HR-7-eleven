-- ---------- [1] ส่วนของแบบประเมิน (10 ส่วน) ----------
-- weight  = น้ำหนักคะแนน รวมทุกส่วนควรได้ 100
-- draw_n  = จำนวนข้อที่สุ่มในแต่ละรอบ (0 = ถามทุกข้อในส่วนนั้น ไม่สุ่ม)
-- gate_min= คะแนนขั้นต่ำของส่วนนี้ ต่ำกว่านี้ถือว่าไม่ผ่านแม้คะแนนรวมจะถึง (null = ไม่กั้น)
create table if not exists public.iv_section (
  key      text primary key,
  name     text not null,
  weight   int  not null default 10,
  draw_n   int  not null default 1,
  sort     int  not null default 0,
  gate_min int,
  active   boolean not null default true
);

-- ---------- [2] คลังคำถาม ----------
-- position ว่าง = ใช้กับทุกตำแหน่ง · ใส่ชื่อตำแหน่ง = ถามเฉพาะตำแหน่งนั้น
create table if not exists public.iv_question (
  id          bigserial primary key,
  section     text not null references public.iv_section(key) on update cascade,
  position    text not null default '',
  question    text not null,
  probe       text not null default '',
  good_answer text not null default '',
  sort        int  not null default 0,
  active      boolean not null default true,
  created_at  timestamptz default now()
);
create index if not exists iv_question_pick_idx on public.iv_question(section, active, sort);

-- ---------- [3] ข้อตัดสิทธิ์ ----------
create table if not exists public.iv_knockout (
  id     bigserial primary key,
  label  text not null,
  sort   int  not null default 0,
  active boolean not null default true
);

-- ---------- [4] เกณฑ์ผ่าน (ตั้งแยกรายตำแหน่งได้) ----------
-- position ว่าง = ค่ากลางใช้กับทุกตำแหน่งที่ไม่ได้ตั้งไว้เอง
create table if not exists public.iv_config (
  position   text primary key default '',
  pass_pct   int not null default 70,
  updated_at timestamptz default now(),
  updated_by text default ''
);

-- ---------- [5] รอบสัมภาษณ์ (1 ผู้สมัคร = 1 รอบ) ----------
-- questions = ชุดคำถามที่สุ่มแล้ว "ล็อก" ไว้ เปิดซ้ำได้ชุดเดิม
-- scores    = {"<question_id>": 1-5}  (0 หรือไม่มีคีย์ = ไม่ได้ถาม ไม่นับคะแนน)
create table if not exists public.iv_session (
  id            bigserial primary key,
  applicant_id  bigint not null,
  branch_id     text not null default '',
  position      text not null default '',
  interviewer   text not null default '',
  questions     jsonb not null default '[]'::jsonb,
  scores        jsonb not null default '{}'::jsonb,
  knockouts     jsonb not null default '[]'::jsonb,
  note          text not null default '',
  total_pct     numeric,
  section_pct   jsonb not null default '{}'::jsonb,
  result        text,                       -- pass / fail / null = ยังไม่สรุป
  fail_reason   text not null default '',   -- เหตุผลภายใน ผู้สมัครไม่เห็น
  started_at    timestamptz default now(),
  submitted_at  timestamptz,
  decided_by    text not null default '',
  sms_sent_at   timestamptz,
  unique (applicant_id)
);
create index if not exists iv_session_br_idx on public.iv_session(branch_id, started_at desc);

