-- ลบบันทึกแจ้งเตือน "ลืมกดออก" ของวันนี้ (รีเซ็ตให้เตือนใหม่ได้)
delete from public.notify_sent
where event_key like 'nocheckout:%'
  and right(event_key, 10) = to_char((now() at time zone 'Asia/Bangkok')::date, 'YYYY-MM-DD');

